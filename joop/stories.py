def mark(text: str) -> str:
    """«[[слово]]» → red tag, «{{слово}}» → white tag; everything else is escaped by the template first."""
    from markupsafe import Markup, escape

    out = escape(text)
    out = _RED.sub(lambda m: f'<i class="r">{m.group(1)}</i>', out)
    out = _WHITE.sub(lambda m: f'<i class="w">{m.group(1)}</i>', out)
    return Markup(out)


def all_slides() -> list[dict[str, Any]]:
    """Flat list with set key, set title and a running number."""
    out: list[dict[str, Any]] = []
    for group in SETS:
        for i, slide in enumerate(group["slides"], 1):
            out.append({**slide, "set": group["key"], "set_title": group["title"], "n": len(out) + 1,
                        "name": f"{group['key']}-{i:02d}"})
    return out
