KY_PATTERNS = [  # (the Russian sentence with its names and numbers, its Kyrgyz with the same in {0}, {1}…)
    (r"Пароль должен быть не короче (\d+) символов\.", "Сырсөз кеминде {0} белгиден турушу керек."),
    (r"Не больше (\d+) входов на компанию\.", "Бир компанияга {0} кирүүдөн ашпайт."),
    (r"Квитанция №(.+) уже есть\.", "№{0} квитанция бар."),
    (r"Заказ уже «(.+)»\.", "Буйрутма мурунтан эле «{0}»."),
    (r"Бронируем с (.+) и не дальше чем на год вперёд\.", "{0} баштап жана бир жылдан ашпай брондойбуз."),
    (r"«(.+)» вмещает до (\d+) гостей\.", "«{0}» {1} конокко чейин батат."),
    (r"«(.+)» на эти даты уже занят\.", "«{0}» бул күндөрү бош эмес."),
    (r"«(.+)»: на эти даты свободных нет\.", "«{0}»: бул күндөрү бошу жок."),
    (r"(.+) не подключён в разделе «Каналы»\.", "{0} «Каналы» бөлүмүндө туташтырылган эмес."),
    (r"(.+) не принял сообщение\. Попробуйте ещё раз или позвоните клиенту\.",
     "{0} билдирүүнү кабыл алган жок. Дагы бир жолу аракет кылыңыз же кардарга чалыңыз."),
]
_PATTERNS = [(re.compile(rf"^{ru}$"), ky) for ru, ky in KY_PATTERNS]


def kyrgyz(text: str) -> str:
    """The refusal in Kyrgyz, or as it was when it is not known."""
    if text in KY_ERRORS:
        return KY_ERRORS[text]
    for pattern, ky in _PATTERNS:
        found = pattern.match(text)
        if found:
            return ky.format(*found.groups())
    return text
